# Builds TrafficCrewFix: (1) a TweakXL yaml that gives faction-themed traffic vehicles a crew of that
# faction when their crew is civilian, and (2) the list of VSF entries to switch off (heat/reinforcement/
# quest/scene records and records that do not exist). Input: vsfpax.json (CET dump of randomPassengers)
# and paxfam.json (passenger entries known to exist). Usage: traffic_crews.py <vsfpax.json> <paxfam.json> <outdir>
import json, re, sys, os

rows = json.load(open(sys.argv[1]))
fams = json.load(open(sys.argv[2]))
out = sys.argv[3]
os.makedirs(out, exist_ok=True)

CIVILIAN = re.compile(r'^(Corporat|Generic|Premium|Lowlife\w*|CitizenRich|NightLife\w*|WorkerSpecialist|CharterHill|CityCenterVIP)$')

# Records that should not drive around as ordinary traffic.
DISABLE = re.compile(r'^(leo_|GR_|RS_|max_tac_av|cs_savable_|hackable_|ep1_hackable_|NGPlus_|sobchak|reed_car|sa_ep1|q\d{3}_)'
                     r'|_prevention(_\d+)?$|_heat_\d|_quest$|_mq\d|_sts_|_heist$|_mws$|^Militech$')

# keyword -> (driver, front, back, biker driver); order matters (first match wins)
FACTIONS = [
    (r'maxtac|max_tac',           'MaxTac'),
    (r'trauma',                   'Trauma'),
    (r'netwatch',                 'NetWatch'),
    (r'border',                   'Border'),
    (r'sheriff',                  'Sheriff'),
    (r'black_agent|detective',    'Detective'),
    (r'police|ncpd|_law\b|_law$|streetkid', 'police'),
    (r'arasaka',                  'ArasakaSecurity'),
    (r'kangtao',                  'Kangtao'),
    (r'kurtz|militia',            'EP1Kurtz'),
    (r'militech',                 'Militech'),
    (r'tyger|tiger',              'Tyger'),
    (r'maelstrom',                'Maelstrom'),
    (r'valentino',                'Valentinos'),
    (r'animals',                  'Animals'),
    (r'_mox|mox_|\bmox',          'Mox'),
    (r'scav',                     'Scavengers'),
    (r'voodoo',                   'Voodoo'),
    (r'wraith',                   'Wraith'),
    (r'sixth|6th',                'Sixthstreet'),
    (r'aldecaldo|adelcaldo',      'Adelcaldos'),
    (r'barghest',                 'Barghest'),
]
# Livery-only corporate dealer cars stay civilian.
SKIP_CREW = re.compile(r'^vcd_corpo_|^vcd_herrera_|_courier$')

def have(name):
    return any(name in v for v in fams.values())

def crew(fam, slots, bike):
    d, f, b = (f'Passengers.{fam}DriverEntry', f'Passengers.{fam}PassengerFrontEntry', f'Passengers.{fam}PassengerBackEntry')
    if fam == 'EP1Kurtz':
        f = 'Passengers.EP1KurtzFrontEntry'
    if fam == 'NetWatch':
        b = f  # no back entry exists
    if bike:
        # bike seats need a biker entry; without one the bike keeps its civilian rider
        bikers = [c for c in (f'Passengers.{fam}BikerDriverEntry', f'Passengers.{fam.lower()}BikerDriverEntry') if have(c)]
        if not bikers:
            return None
        d = bikers[0]
    seats = [d, f, b][:max(1, min(slots, 3))]
    return seats if all(have(s) for s in seats) else None

disable, fixes, skipped = [], {}, []
for name, pax in sorted(rows.items()):
    if pax == 'NORECORD' or DISABLE.search(name):
        disable.append(name)
        continue
    pfams = {re.sub(r'(Driver|Passenger|Biker|Guard).*', '', p.split('.', 1)[1]) for p in pax}
    if not pax or not all(CIVILIAN.match(x) for x in pfams) or SKIP_CREW.search(name):
        continue
    # 'militech_hellhound' / 'militech_behemoth' name the manufacturer, not the faction
    lname = re.sub(r'militech_(hellhound|behemoth)', r'\1', name.lower())
    for kw, fam in FACTIONS:
        if re.search(kw, lname):
            bike = bool(re.search(r'bike|apollo|arch_|nemesis|kusanagi|fyrn|mogus|paladin', lname)) and len(pax) <= 1
            c = crew(fam, len(pax), bike)
            if c:
                fixes[name] = (fam, pax, c)
            else:
                skipped.append((name, fam))
            break

with open(os.path.join(out, 'TrafficCrewFix.yaml'), 'w', newline='\n') as y:
    y.write('# Traffic Crew Fix (2026-10-04): faction-themed traffic vehicles that had a civilian crew get a crew\n'
            '# of their faction (crew lists use passenger entries that exist in this load order).\n'
            '# Generated by tools/traffic_crews.py from a CET dump of randomPassengers.\n\n')
    for name, (fam, old, new) in fixes.items():
        y.write(f'# was: {" ".join(p.split(".")[1] for p in old)}\n')
        y.write(f'Vehicle.{name}.randomPassengers: [{", ".join(new)}]\n\n')
json.dump(disable, open(os.path.join(out, 'vsf_disable.json'), 'w'), indent=0)
print('crew fixes', len(fixes), 'vsf disable', len(disable), 'no crew available', skipped)
for n, (fam, o, c) in list(fixes.items())[:200]:
    print(f'  {n:60s} -> {fam} x{len(c)}')
